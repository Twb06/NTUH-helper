/* eslint-env node */

const fs = require("node:fs");
const path = require("node:path");

const projectRoot = path.resolve(__dirname, "..");
const ocrPath = path.join(projectRoot, "scripts/lib/login-ocr.js");
const sourcePath = path.join(projectRoot, "scripts/src/login-helper.user.js");
const outputPath = path.join(projectRoot, "scripts/login-helper.user.js");
const legacyOutputPath = path.join(projectRoot, "scripts/login-ocr.user.js");

function read(pathname) {
    return fs.readFileSync(pathname, "utf8").trim();
}

function splitMetadata(userscript) {
    const match = userscript.match(/^(\/\/ ==UserScript==[\s\S]*?\/\/ ==\/UserScript==)\s*([\s\S]*)$/);
    if (!match) throw new Error("找不到 login-helper userscript metadata");
    return { metadata: match[1], body: match[2] };
}

const ocr = read(ocrPath);
const source = splitMetadata(read(sourcePath));
const output = [
    source.metadata,
    "// Generated by tools/build-login-helper.js. Edit scripts/src/login-helper.user.js or scripts/lib/login-ocr.js.",
    ocr,
    source.body
].join("\n\n");

fs.writeFileSync(outputPath, `${output}\n`);
fs.writeFileSync(legacyOutputPath, `${output}\n`);
console.log(`已產生 ${path.relative(projectRoot, outputPath)}`);
console.log(`已產生舊版更新入口 ${path.relative(projectRoot, legacyOutputPath)}`);
